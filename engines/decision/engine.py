"""
Decision Engine — Make data-driven business decisions using structured evaluation
"""
from __future__ import annotations
from typing import Any
from engines.base import BaseEngine, EngineStep, StepResult, EngineStatus
from models.routing.model_router import ModelRouter


class DecisionEngine(BaseEngine):
    engine_name = "decision"
    required_input_fields = ['options', 'evaluation_criteria']
    required_output_fields = ['decision', 'rationale']

    def __init__(self) -> None:
        self._model_router = ModelRouter()
        super().__init__()

    def define_steps(self) -> None:
        self.flow.add_step(EngineStep(name="analyze", model_role="analyzer", description="Analyze decision options", required=True, stop_on_reject=True))
        self.flow.register_executor("analyze", self._step_analyze)
        self.flow.add_step(EngineStep(name="execute", model_role="worker", description="Evaluate and select best option", required=True))
        self.flow.register_executor("execute", self._step_execute)
        self.flow.add_step(EngineStep(name="enhance", model_role="creative", description="Enhance with strategic narrative", required=False))
        self.flow.register_executor("enhance", self._step_enhance)
        self.flow.add_step(EngineStep(name="validate", model_role="validator", description="Validate decision logic", required=True))
        self.flow.register_executor("validate", self._step_validate)

    def _step_analyze(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("analyze", data)
        r = self._model_router.execute("analyzer", prompt, context=data)
        return StepResult(step_name=step_name, model_used="mistral", status=EngineStatus.COMPLETED, output={"analysis": r})

    def _step_execute(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("execute", data)
        r = self._model_router.execute("worker", prompt, context=data)
        return StepResult(step_name=step_name, model_used="qwen", status=EngineStatus.COMPLETED, output={"execution": r})

    def _step_enhance(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("enhance", data)
        r = self._model_router.execute("creative", prompt, context=data)
        return StepResult(step_name=step_name, model_used="llama", status=EngineStatus.COMPLETED, output={"enhanced": r})

    def _step_validate(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("validate", data)
        r = self._model_router.execute("validator", prompt, context=data)
        return StepResult(step_name=step_name, model_used="mistral", status=EngineStatus.COMPLETED, output={"validation": r})

    def _build_prompt(self, step: str, data: dict[str, Any]) -> str:
        templates = {"analyze": """Analyze: options (pros/cons/risks/costs), evaluation criteria and weights, constraints, reversibility.\nOptions: {options}\nCriteria: {evaluation_criteria}""", "execute": """Score options against criteria, rank, select winner. Include: decision matrix, sensitivity analysis, what-if for top 2.\nAnalysis: {analysis}""", "enhance": """Enhance: compelling rationale narrative, confidence level, dissenting argument addressed.\nDecision: {execution}""", "validate": """Validate: scoring is consistent, criteria weights sum to 1, no confirmation bias, reversibility considered.\nOutput: {enhanced}"""}
        t = templates.get(step, "")
        try:
            return t.format(**data)
        except KeyError:
            return t + "\nData: " + str(data)

    @staticmethod
    def _decision_matrix(options: list[str], criteria: dict[str, float], scores: dict[str, dict[str, float]]) -> dict[str, float]:
        results = {}
        for opt in options:
            total = sum(scores.get(opt, {}).get(c, 0) * w for c, w in criteria.items())
            results[opt] = round(total, 3)
        return results
