"""
Psychology Engine — Apply behavioral psychology principles to optimize user journeys
"""
from __future__ import annotations
from typing import Any
from engines.base import BaseEngine, EngineStep, StepResult, EngineStatus
from models.routing.model_router import ModelRouter


class PsychologyEngine(BaseEngine):
    engine_name = "psychology"
    required_input_fields = ['behavior_data', 'journey_stage']
    required_output_fields = ['psychological_triggers', 'recommendations']

    def __init__(self) -> None:
        self._model_router = ModelRouter()
        super().__init__()

    def define_steps(self) -> None:
        self.flow.add_step(EngineStep(name="analyze", model_role="analyzer", description="Analyze behavioral patterns and decision biases", required=True, stop_on_reject=True))
        self.flow.register_executor("analyze", self._step_analyze)
        self.flow.add_step(EngineStep(name="execute", model_role="worker", description="Generate psychology-informed UX recommendations", required=True))
        self.flow.register_executor("execute", self._step_execute)
        self.flow.add_step(EngineStep(name="enhance", model_role="creative", description="Enhance with nuanced behavioral nudges", required=False))
        self.flow.register_executor("enhance", self._step_enhance)
        self.flow.add_step(EngineStep(name="validate", model_role="validator", description="Validate ethical boundaries", required=True))
        self.flow.register_executor("validate", self._step_validate)

    def _step_analyze(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("analyze", data)
        result = self._model_router.execute("analyzer", prompt, context=data)
        return StepResult(step_name=step_name, model_used="mistral", status=EngineStatus.COMPLETED, output={"analysis": result})

    def _step_execute(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("execute", data)
        result = self._model_router.execute("worker", prompt, context=data)
        return StepResult(step_name=step_name, model_used="qwen", status=EngineStatus.COMPLETED, output={"execution": result})

    def _step_enhance(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("enhance", data)
        result = self._model_router.execute("creative", prompt, context=data)
        return StepResult(step_name=step_name, model_used="llama", status=EngineStatus.COMPLETED, output={"enhanced": result})

    def _step_validate(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("validate", data)
        result = self._model_router.execute("validator", prompt, context=data)
        return StepResult(step_name=step_name, model_used="mistral", status=EngineStatus.COMPLETED, output={"validation": result})

    def _build_prompt(self, step: str, data: dict[str, Any]) -> str:
        templates = {"analyze": """Analyze: cognitive biases at play, decision fatigue points, choice architecture, emotional state per journey stage.\nBehavior: {behavior_data}\nStage: {journey_stage}""", "execute": """Generate: bias-leveraging tactics per stage (anchoring, framing, social proof, scarcity, loss aversion), implementation specifications.\nAnalysis: {analysis}""", "enhance": """Enhance: subtle micro-copy changes, visual hierarchy adjustments, timing of nudges.\nTactics: {execution}""", "validate": """Validate: ethically sound (no dark patterns), transparent, reversible, genuinely helpful to user.\nOutput: {enhanced}"""}
        t = templates.get(step, "")
        try:
            return t.format(**data)
        except KeyError:
            return t + "\nData: " + str(data)

    COGNITIVE_BIASES = ["anchoring", "social_proof", "scarcity", "loss_aversion", "framing", "reciprocity", "commitment", "authority", "bandwagon", "default"]
