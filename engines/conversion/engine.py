"""
Conversion Engine — Maximize conversion rates across all touchpoints
"""
from __future__ import annotations
from typing import Any
from engines.base import BaseEngine, EngineStep, StepResult, EngineStatus
from models.routing.model_router import ModelRouter


class ConversionEngine(BaseEngine):
    engine_name = "conversion"
    required_input_fields = ['conversion_data', 'touchpoints']
    required_output_fields = ['conversion_plan', 'predicted_rates']

    def __init__(self) -> None:
        self._model_router = ModelRouter()
        super().__init__()

    def define_steps(self) -> None:
        self.flow.add_step(EngineStep(name="analyze", model_role="analyzer", description="Analyze conversion bottlenecks", required=True, stop_on_reject=True))
        self.flow.register_executor("analyze", self._step_analyze)
        self.flow.add_step(EngineStep(name="execute", model_role="worker", description="Generate conversion optimization plan", required=True))
        self.flow.register_executor("execute", self._step_execute)
        self.flow.add_step(EngineStep(name="enhance", model_role="creative", description="Enhance with psychological triggers", required=False))
        self.flow.register_executor("enhance", self._step_enhance)
        self.flow.add_step(EngineStep(name="validate", model_role="validator", description="Validate predicted conversion improvements", required=True))
        self.flow.register_executor("validate", self._step_validate)

    def _step_analyze(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("analyze", data)
        result = self._model_router.execute("analyzer", prompt, context=data)
        return StepResult(step_name=step_name, model_used="mistral", status=EngineStatus.COMPLETED, output={"analysis": result})

    def _step_execute(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("execute", data)
        result = self._model_router.execute("worker", prompt, context=data)
        return StepResult(step_name=step_name, model_used="qwen", status=EngineStatus.COMPLETED, output={"execution": result})

    def _step_enhance(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("enhance", data)
        result = self._model_router.execute("creative", prompt, context=data)
        return StepResult(step_name=step_name, model_used="llama", status=EngineStatus.COMPLETED, output={"enhanced": result})

    def _step_validate(self, step_name: str, data: dict[str, Any]) -> StepResult:
        prompt = self._build_prompt("validate", data)
        result = self._model_router.execute("validator", prompt, context=data)
        return StepResult(step_name=step_name, model_used="mistral", status=EngineStatus.COMPLETED, output={"validation": result})

    def _build_prompt(self, step: str, data: dict[str, Any]) -> str:
        templates = {"analyze": """Analyze: conversion rates per touchpoint, device split, time-to-convert, micro-conversion steps, heat map patterns.\nData: {conversion_data}\nTouchpoints: {touchpoints}""", "execute": """Generate: per-touchpoint CRO plan, A/B test hypotheses (5), copy changes, layout recommendations, CTA optimization.\nAnalysis: {analysis}""", "enhance": """Enhance: scarcity, social proof, authority, reciprocity, commitment/consistency triggers.\nPlan: {execution}""", "validate": """Validate: predicted lifts are conservative (2-15% per change), tests are statistically valid, no conflicting changes.\nOutput: {enhanced}"""}
        t = templates.get(step, "")
        try:
            return t.format(**data)
        except KeyError:
            return t + "\nData: " + str(data)

    @staticmethod
    def _conversion_rate(visitors: int, conversions: int) -> float:
        return round(conversions / max(visitors, 1) * 100, 2)

    @staticmethod
    def _lift_estimate(baseline: float, improvement_pct: float) -> float:
        return round(baseline * (1 + improvement_pct / 100), 2)
